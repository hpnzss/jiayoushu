const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path'),os=require('node:os');
const {openLedger}=require('./ledger.cjs');
const {openExpenses}=require('./expenses.cjs');
const E=require('./prototype/expenses-report.js');
const dir=fs.mkdtempSync(path.join(os.tmpdir(),'family-expenses-')),file=path.join(dir,'test.sqlite');
let ledger,expenses,sequence=0;
const summary=(extra={})=>({requestId:'expense-month-'+(++sequence),expectedRevision:0,month:'2026-01',through:'2026-01-31',amount:'100.00',memo:'合成测试',...extra});
try{
  ledger=openLedger(file);expenses=openExpenses(file);
  const before=JSON.stringify(ledger.state().balances);
  const input=summary();assert.equal(expenses.save(input).summary.scope,'household');assert.equal(expenses.save(input).alreadySaved,true);
  assert.equal(expenses.list().length,1);
  expenses.save(summary({amount:'200.00',expectedRevision:1}));
  assert.equal(expenses.list().length,1,'同月修改只保留一个现行家庭总额');
  assert.equal(expenses.list()[0].cents,20000);
  assert.equal(JSON.stringify(ledger.state().balances),before,'月总额不扣余额');
  assert.throws(()=>expenses.save(summary()),/已被更新/);
  assert.throws(()=>expenses.save(summary({member:'成员一',expectedRevision:2})),/仅支持/);
  assert.throws(()=>expenses.save(summary({mode:'itemized',expectedRevision:2})),/仅支持/);
  assert.throws(()=>expenses.save(summary({through:'2026-02-01',expectedRevision:2})),/截止/);
  assert.throws(()=>ledger.preview({format:'family-assets-import',version:2,batchId:'disabled-detail-001',records:[{type:'expense',date:'2026-01-05',account:'a',amount:'20.00',member:'成员一',category:'餐饮'}]}),/不支持逐笔/);
  const transfer={type:'transfer',date:'2026-01-05',feeCents:200};
  let r=E.report([transfer],expenses.list(),'2026-01-01','2026-01-31');assert.equal(r.cents,20000,'总额包含手续费，不额外叠加');
  assert.equal(E.report([],expenses.list(),'2026-01-02','2026-01-31').cents,null,'截断月总额不能伪造日均分摊');
  assert.equal(E.report([],expenses.list(),'2026-01-01','2026-01-31','成员一').cents,20000,'成员筛选不改变家庭支出');
  expenses.save(summary({month:'2026-02',through:'2026-02-28',amount:'0.00'}));
  assert.equal(E.report([],expenses.list(),'2026-02-01','2026-02-28').cents,0,'明确零支出');
  assert.equal(E.report([],expenses.list(),'2026-03-01','2026-03-31').cents,null,'未填不等于0');
  const legacy=[{member:'成员一',month:'2026-01',mode:'total',through:'2026-01-31',cents:5000},{member:'成员二',month:'2026-01',mode:'total',through:'2026-01-31',cents:6000}];
  assert.equal(E.report([],legacy,'2026-01-01','2026-01-31').cents,11000,'旧总额可读');
  assert.equal(E.report([],legacy.concat(expenses.list()),'2026-01-01','2026-01-31').cents,20000,'新家庭总额替代旧成员总额');
  expenses.close();expenses=openExpenses(file);assert.equal(expenses.list().length,2,'重启保留');
  const D=require('./prototype/report.js');
  D.load({accounts:[{id:'a',name:'测试银行',owner:'成员一',currency:'CNY'}],balances:[],adjustments:[],incomes:[{date:'2026-01-10',member:'成员一',source:'工资',account:'a',cents:300000}],records:[],expenseSummaries:[{scope:'household',member:'共同',month:'2026-01',mode:'total',through:'2026-01-31',cents:100000}],snapshots:[{date:'2025-12-31',amounts:[10000000],complete:true},{date:'2026-01-31',amounts:[10200000],complete:true}]});
  assert.equal(D.report('2026-01-01','2026-01-31').gap,0);
  assert.equal(D.report('2026-01-01','2026-01-31','成员二').gap,0);
  assert.equal(D.report('2026-01-05','2026-01-31').gap,null);
  console.log('月度支出检查通过：全家每月一笔、修改不累加、不扣余额、并发与重复保护、禁用逐笔、手续费不重复、零与未填、日期边界、旧数据兼容及家庭差额。');
}finally{ledger?.close();expenses?.close();fs.rmSync(dir,{recursive:true,force:true});}
