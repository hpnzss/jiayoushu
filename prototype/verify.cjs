const assert = require('node:assert/strict');
const D = require('./report.js');
const year = D.report('2026-01-01', '2026-10-15');
assert.equal(year.income, 30000000);
assert.equal(D.total(year.opening), 18500000);
assert.equal(D.total(year.closing), 29750000);
assert.equal(year.delta, 11250000);
assert.equal(year.gap, -18750000);
const a = D.report('2026-01-01', '2026-10-15', '成员一');
const b = D.report('2026-01-01', '2026-10-15', '成员二');
assert.equal(a.income + b.income, year.income);
assert.equal(a.delta, year.delta);
assert.equal(a.gap, year.gap);
const single = D.report('2026-10-15', '2026-10-15');
assert.equal(single.income, 1200000);
assert.equal(single.opening.date, '2026-09-30');
assert.equal(single.closing.date, '2026-10-15');
const noBaseline = D.report('2025-01-01', '2025-06-30');
assert.equal(noBaseline.closing, null);
assert.equal(noBaseline.delta, null);
assert.equal(noBaseline.income, 0);
const future = D.report('2027-01-01', '2027-12-31');
assert.equal(future.closing.date, '2026-10-15');
assert.equal(future.points.length, 0);
assert.equal(future.income, 0);
assert.throws(() => D.report('2026-10-15', '2026-01-01'));
console.log('报告检查通过：家庭与个人汇总、单日边界、缺失期初、旧值沿用、日期倒置。');
